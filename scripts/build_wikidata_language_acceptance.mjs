import { writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

function argument(name, fallback) {
  const index = process.argv.indexOf(name);
  return index >= 0 && process.argv[index + 1] ? process.argv[index + 1] : fallback;
}

const endpoint = "https://query.wikidata.org/sparql";
const definitions = [
  ["ar", "عربی"], ["he", "عبری"], ["zh", "چینی"], ["ja", "ژاپنی"],
  ["ru", "روسی"], ["de", "آلمانی"], ["fr", "فرانسوی"], ["es", "اسپانیایی"],
];
const requestedPerLanguage = Math.max(1, Math.min(500,
  Number.parseInt(argument("--per-language", "200"), 10) || 200));
const offset = Math.max(0, Number.parseInt(argument("--offset", "0"), 10) || 0);
const outputPath = resolve(argument("--output", "server/data/wikidata-language-acceptance.mjs"));
const excludePath = argument("--exclude", "");
const excludedItems = new Set();
if (excludePath) {
  const excluded = (await import(pathToFileURL(resolve(excludePath)).href)).default;
  for (const language of excluded.languages || []) {
    for (const item of language.items || []) excludedItems.add(item.item);
  }
}

function normalized(value) {
  return String(value || "").normalize("NFKC").trim().replace(/\s+/g, " ").toLocaleLowerCase("und");
}

async function queryLanguage(language, attempt = 1) {
  const query = `SELECT DISTINCT ?item ?source ?target WHERE {
    ?item wdt:P31 wd:Q515; rdfs:label ?source; rdfs:label ?target.
    FILTER(LANG(?source) = "${language}")
    FILTER(LANG(?target) = "fa")
    FILTER(STR(?source) != STR(?target))
  } ORDER BY ?item LIMIT ${requestedPerLanguage * 3} OFFSET ${offset}`;
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 60_000);
  timeout.unref?.();
  try {
    const response = await fetch(`${endpoint}?query=${encodeURIComponent(query)}&format=json`, {
      headers: { accept: "application/sparql-results+json", "user-agent": "TranslatorLab-Evaluation/0.1" },
      signal: controller.signal,
    });
    if (!response.ok) throw new Error(`wikidata_${response.status}`);
    const payload = await response.json();
    const seenSource = new Set();
    const items = [];
    for (const binding of payload.results?.bindings || []) {
      const sourceName = binding.source?.value?.trim();
      const expected = binding.target?.value?.trim();
      const item = binding.item?.value?.split("/").pop();
      const key = normalized(sourceName);
      if (!item || excludedItems.has(item) || !key || !expected || seenSource.has(key)) continue;
      seenSource.add(key);
      items.push({ item, sourceName, expected, layer: "place", className: "city" });
      if (items.length >= requestedPerLanguage) break;
    }
    return { query, items };
  } catch (error) {
    if (attempt >= 2) throw error;
    await new Promise((resolve) => setTimeout(resolve, 2_000));
    return queryLanguage(language, attempt + 1);
  } finally {
    clearTimeout(timeout);
  }
}

const languages = [];
for (const [language, label] of definitions) {
  const result = await queryLanguage(language);
  languages.push({ language, label, requested: requestedPerLanguage, items: result.items });
  console.log(`${language}: ${result.items.length}`);
  await new Promise((resolve) => setTimeout(resolve, 750));
}

const output = { version: 1, generatedAt: new Date().toISOString(), endpoint,
  entityClass: "Q515", requestedPerLanguage, offset, excludedItems: excludedItems.size, languages };
const body = `// Generated by scripts/build_wikidata_language_acceptance.mjs\nexport default ${JSON.stringify(output)};\n`;
await writeFile(outputPath, body, "utf8");
console.log(JSON.stringify({ generatedAt: output.generatedAt,
  outputPath, counts: Object.fromEntries(languages.map((entry) => [entry.language, entry.items.length])) }, null, 2));
